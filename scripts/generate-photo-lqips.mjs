/**
 * Soft LQIP data URLs for photo blur-up.
 * Larger / less crushed than next/image's default blurDataURL.
 *
 * Usage: node scripts/generate-photo-lqips.mjs
 */
import sharp from "sharp";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "public", "ace");
const out = path.join(root, "lib", "photo-lqips.ts");

const keys = [
  "ace-shooter-promax",
  "air-combat-bg",
  "air-combat",
  "bikers-madness",
  "cold-trigger",
  "crossbow-fishing",
  "dragon-kingdom-vr",
  "exhibitions",
  "featured-video",
  "galaxy-rangers",
  "hoop-hustle",
  "jet-ski-racer",
  "machine",
  "medal-master",
  "network",
  "news-guangzhou-arcade",
  "news-zhongshan-booth",
  "news-zhongshan-floor",
  "partner-cta",
  "pop-shot-circus",
  "racing-xtreme",
  "roll-n-win",
  "skull-of-shadow",
  "speedy-toss",
  "thunder-jets",
  "wild-frontier",
  "wild-hunting",
];

const lines = [
  "/** Soft LQIP data URLs — larger/less crushed than next/image blurDataURL.",
  " *  Regenerated by: node scripts/generate-photo-lqips.mjs",
  " */",
  "export const photoLqips = {",
];

for (const name of keys) {
  const file = path.join(dir, `${name}.webp`);
  if (!fs.existsSync(file)) {
    console.warn("missing", file);
    continue;
  }
  const buf = await sharp(file)
    .resize({ width: 64, withoutEnlargement: true })
    .blur(1.2)
    .webp({ quality: 45, alphaQuality: 70 })
    .toBuffer();
  const data = `data:image/webp;base64,${buf.toString("base64")}`;
  lines.push(`  "/ace/${name}.webp": ${JSON.stringify(data)},`);
  console.log(`${name}: ${buf.length}B`);
}

lines.push(
  "} as const;",
  "",
  "export type PhotoLqipPath = keyof typeof photoLqips;",
  "",
  "export function resolveLqip(src: string): string | null {",
  '  const q = src.indexOf("?");',
  "  let path = q >= 0 ? src.slice(0, q) : src;",
  "  try {",
  '    if (/^https?:\\/\\//i.test(path)) path = new URL(path).pathname;',
  "  } catch { /* keep */ }",
  '  if (!path.startsWith("/")) path = `/${path}`;',
  "  return (photoLqips as Record<string, string>)[path] ?? null;",
  "}",
  "",
);

fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(root, out)}`);
